def generate_dataset():
    if not os.path.exists(DATA_DIR):
        os.makedirs(DATA_DIR, exist_ok=True)

    records = []
    print(f"Compiling {len(QUESTIONS_AND_ANSWERS)} diverse Pakistani cultural Q&A records...")

    for idx, (question, answer, category, is_roman) in enumerate(QUESTIONS_AND_ANSWERS, start=1):
        # Validation checks
        assert len(question.strip()) > 5, f"Question {idx} too short"
        assert len(answer.strip()) > 30, f"Answer {idx} too short"
        # Zero emojis check
        assert not bool(re.search(r'[\U00010000-\U0010ffff\u2600-\u27bf]', answer)), f"Emoji detected in answer {idx}"
        # Respectful "آپ" check (standalone disrespectful pronoun check)
        self_respect_violation = bool(re.search(r'(?<![\u0600-\u06ff])(?:تم|تمہیں|تمہارا|تمہاری|تمہارے|تیرا|تیری)(?![\u0600-\u06ff])', answer))
        assert not self_respect_violation, f"Disrespectful pronoun in answer {idx}"

        record = {
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": question.strip()},
                {"role": "assistant", "content": answer.strip()}
            ],
            "metadata": {
                "id": idx,
                "category": category.strip(),
                "question": question.strip(),
                "response_length": len(answer.strip()),
                "language_pair": "Roman_Urdu_to_Nastaliq" if is_roman else "Urdu_to_Urdu"
            }
        }
        records.append(record)

    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    print(f"[OK] Successfully wrote {len(records)} pristine Q&A records to {OUTPUT_FILE}!")

    # Rebuild master dataset using dataset_manager
    try:
        from dataset_manager import build_master_dataset, load_dataset_records, MASTER_DATASET_FILE
        master_path = build_master_dataset()
        master_records = load_dataset_records(master_path)
        print(f"[OK] Master training dataset refreshed at {master_path}: Total {len(master_records)} unique records!")
    except Exception as e:
        print(f"Warning: Could not refresh master dataset via dataset_manager: {e}")


if __name__ == "__main__":
    generate_dataset()
